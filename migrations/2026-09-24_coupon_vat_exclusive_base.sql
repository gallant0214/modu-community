-- 정률 쿠폰의 할인 기준을 쿠폰마다 고를 수 있게 (2026-09-24)
--
-- 범어점은 헬스 회원권에 한해 재등록 회원에게 부가세를 청구하지 않는다.
-- 그 용도의 '재등록 10% 할인 쿠폰'은 정가가 아니라 **공급가액(부가세 제외)** 의 10% 를
-- 깎아야 부가세만큼 정확히 빠진다.
--   1개월(신규) 77,000 = 공급가 70,000 + 부가세 7,000 → 10% 할인 7,000원 → 70,000원 결제
--
-- 상품 유형으로 자동 판정하지 않고 쿠폰 설정으로 둔 이유:
-- 나중에 회원권에 '진짜 10%' 쿠폰을 주고 싶을 수도 있고, 규칙이 화면에 보여야 헷갈리지 않는다.
ALTER TABLE crm_coupons
  ADD COLUMN IF NOT EXISTS vat_exclusive_base boolean NOT NULL DEFAULT false;
