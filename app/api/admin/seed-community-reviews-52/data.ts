export const newPosts: SeedPost[] = RAW_POSTS.map((raw, idx) => {
  const postAuthor = authorAt(idx);
  const ca = commentAuthors(postAuthor, raw.comments.length, idx * 5 + 2);
  return {
    categoryId: 1, // 보디빌딩
    title: raw.title,
    content: raw.content,
    author: postAuthor,
    date: raw.date,
    region: raw.region,
    comments: raw.comments.map((c, i) => ({
      author: ca[i],
      content: c.content,
      hoursOffset: c.hoursOffset,
    })),
  };
});

