export function pickRegion(): string {
  const groups = REGION_GROUPS.filter((g) => WEIGHTS[g.name]);
  const total = groups.reduce((sum, g) => sum + (WEIGHTS[g.name] || 0), 0);
  let r = Math.random() * total;
  let picked = groups[0];
  for (const g of groups) {
    r -= WEIGHTS[g.name] || 0;
    if (r <= 0) {
      picked = g;
      break;
    }
  }
  const sub = picked.subRegions[Math.floor(Math.random() * picked.subRegions.length)];
  return `${picked.name} - ${sub.name}`;
}

