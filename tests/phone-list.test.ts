import { describe, expect, it } from "vitest";
import { parsePhoneList } from "@/app/lib/phone-list";

const P = "01038979784";

describe("parsePhoneList", () => {
  it("명단 원문에서 전화번호만 뽑고 날짜·금액·순번은 버린다", () => {
    const raw = "1\t정초인\t010-3897-9784\t남\t2026-08-05\t3.4\t11\t단골\n2,박도현,01094779282,165000";
    expect(parsePhoneList(raw)).toEqual([P, "01094779282"]);
  });
  it.each([
    ["하이픈", "010-3897-9784"],
    ["숫자만", "01038979784"],
    ["띄어쓰기", "010 3897 9784"],
    ["점", "010.3897.9784"],
    ["괄호", "(010)3897-9784"],
    ["엑셀이 앞자리 0을 지움", "1038979784"],
    ["국가번호 +82", "+82 10-3897-9784"],
    ["국가번호 붙여 씀", "821038979784"],
  ])("휴대폰 %s → 01038979784", (_, raw) => {
    expect(parsePhoneList(raw)).toEqual([P]);
  });
  it("여러 줄·여러 모양이 섞여도 순서대로, 중복은 한 번", () => {
    const raw = "정초인 010-3897-9784\n박도현,01094779282\n김현준 / 010.8236.2760 / 165,000원\n정초인 01038979784";
    expect(parsePhoneList(raw)).toEqual([P, "01094779282", "01082362760"]);
  });
  it("유선·02 지역번호는 예전처럼 인식", () => {
    expect(parsePhoneList("053-755-4455 02-123-4567 02-1234-5678")).toEqual(["0537554455", "021234567", "0212345678"]);
  });
  it("날짜·금액·큰 숫자를 번호로 오인하지 않는다", () => {
    expect(parsePhoneList("2026-11-16 2026.10.27 165000000 1,650,000 16500000 3.4 123-45-67890")).toEqual([]);
  });
  it("옛 10자리 휴대폰(010-123-4567)", () => {
    expect(parsePhoneList("010-123-4567")).toEqual(["0101234567"]);
  });
});
